// =============================================================================
// refresh-live-snapshot.mjs — the LAST-KNOWN payloads of the live market endpoints,
// committed as a data module (dashboard/js/live-snapshot.js) so a card whose live
// call fails (or returns nothing) shows dated last-known values instead of
// "unavailable" — even for a first-time viewer with no browser cache (review
// 2026-10-15, recommendation #1). The per-viewer browser cache (v2/js/live-cache.js)
// still wins when it is newer.
//
// Runs the Worker's OWN handlers outside the Worker (same sources, same shapes as
// production), exactly like refresh-dash-snapshot.mjs. A payload replaces the stored
// one only when it is useful (non-empty); otherwise the previous dated payload stays.
//   node scripts/refresh-live-snapshot.mjs            # writes dashboard/js/live-snapshot.js
//   node scripts/refresh-live-snapshot.mjs --dry-run
// Scheduled in .github/workflows/refresh-dash-snapshot.yml (weekdays).
// =============================================================================
import fs from "node:fs";

const FILE = new URL("../dashboard/js/live-snapshot.js", import.meta.url);
export const ENDPOINTS = ["/api/rates", "/api/eurates", "/api/yield-curve", "/api/govyields", "/api/markets", "/api/predict"];

// Is a payload worth keeping? (Mirrors v2/js/live-cache.js `useful`.)
export function useful(path, d) {
  if (!d || typeof d !== "object") return false;
  if (path === "/api/rates") return Array.isArray(d.rates) && d.rates.some((x) => x && x.value != null);
  if (path === "/api/eurates") return Array.isArray(d.series) && d.series.some((x) => x && x.value != null);
  if (path === "/api/yield-curve") return Array.isArray(d.us) && d.us.some((v) => v != null);
  if (path === "/api/govyields") return Array.isArray(d.yields) && d.yields.some((x) => x && x.y10 && x.y10.v != null);
  if (path === "/api/markets") return Array.isArray(d.markets) && d.markets.some((x) => x && x.value != null);
  if (path === "/api/predict") return Array.isArray(d.markets) && d.markets.some((x) => x && x.yes != null);
  return Object.keys(d).length > 0;
}

export function readSnapshot(src) {
  const m = /export const LIVE_SNAPSHOT = (\{[\s\S]*\});\s*$/.exec(src || "");
  try { return m ? JSON.parse(m[1]) : { payloads: {} }; } catch { return { payloads: {} }; }
}

export function render(snap) {
  return `// AUTO-GENERATED by scripts/refresh-live-snapshot.mjs — do not hand-edit.
// Last-known payloads of the live market endpoints, each with the time it was
// captured (savedAt). Shown, clearly labelled with that time, only when a live call
// fails or returns nothing (v2/js/live-cache.js). Sources are the same free feeds the
// live endpoints read (FRED, ECB Data Portal, BoE, US Treasury, Yahoo Finance).
export const LIVE_SNAPSHOT = ${JSON.stringify(snap)};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  globalThis.caches = { default: { match: async () => null, put: async () => {} } };
  const W = await import("../src/index.js");
  const env = { ASSETS: { fetch: async () => new Response("", { status: 404 }) } };
  const ctx = { waitUntil() {}, passThroughOnException() {} };
  const cur = fs.existsSync(FILE) ? readSnapshot(fs.readFileSync(FILE, "utf8")) : { payloads: {} };
  const now = new Date().toISOString();
  let n = 0;
  for (const p of ENDPOINTS) {
    let d = null;
    try { const r = await W.default.fetch(new Request("https://wire.local" + p), env, ctx); d = r.ok ? await r.json() : null; } catch (e) { console.error(p, String(e).slice(0, 120)); }
    if (useful(p, d)) { cur.payloads[p] = { savedAt: now, data: d }; n++; console.log(`${p}: refreshed`); }
    else console.log(`${p}: nothing useful — kept ${cur.payloads[p] ? cur.payloads[p].savedAt : "none"}`);
  }
  if (!n) { console.error("no endpoint refreshed — snapshot left unchanged"); process.exit(2); }
  if (!process.argv.includes("--dry-run")) fs.writeFileSync(FILE, render(cur));
}
