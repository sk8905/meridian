// =============================================================================
// gen-home-data.mjs — build-time generator for /home-data.js
//
// The Home surface used to import the FULL desk data modules (credit/js/data.js
// ~2.6 MB, legal/js/data.js ~2.4 MB, macro/js/content.js ~0.5 MB = ~5.5 MB raw /
// ~1.5 MB gzip) even though it renders only slices. This projects each record to
// the fields Home + the manager wire actually read, stripping the heavy
// profile/detail bodies Home never shows:
//   • managers: drop sources/book/description/financials/news/advisers/structured/
//     owners/legal/headcount/filings/regSources; project webNews → date/title/url/outlet
//   • deals / intel: drop `summary` (the wire shows the headline; the reader works
//     off the DOM row + /api/read, never the record body)
//   • funds: drop sources/description/notableInvestments/investors (wire shows name + status)
//   • legal items: drop summary/points/tags/areas/jurisdiction/area
//   • legal cases: drop summary ; restructurings: drop features/notes/debt/creditors/advisers
//   • firmById: reduce to { id: { name } } (firmName reads only .name)
//   • macro: kept WHOLE (small — ~169 KB gz — and the snapshot/earnings read it deeply)
//
// Runs FIRST in `npm run build` (before postbuild copies root files into dist), so
// /home-data.js is ALWAYS in sync with the 5×/day data refresh: the refresh edits
// the full modules, the next deploy's build regenerates this. DO NOT hand-edit the
// output. Field NAMES are stable as the data grows, so this stays correct over time.
// =============================================================================
import { writeFileSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { gzipSync } from "node:zlib";
import * as CR from "../credit/js/data.js";
import * as LG from "../legal/js/data.js";
import * as MC from "../macro/js/content.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const omit = (o, keys) => { const r = {}; for (const k in o) if (!keys.includes(k)) r[k] = o[k]; return r; };
const pick = (o, keys) => { const r = {}; for (const k of keys) if (o && o[k] !== undefined) r[k] = o[k]; return r; };

// ---- credit ----------------------------------------------------------------
const MANAGER_DROP = ["sources", "book", "description", "financials", "news", "advisers", "structured", "owners", "legal", "headcount", "filings", "regSources"];
const managers = (CR.managers || []).map((m) => {
  const mm = omit(m, MANAGER_DROP);
  if (Array.isArray(m.webNews)) mm.webNews = m.webNews.map((w) => pick(w, ["date", "title", "url", "outlet"]));
  return mm;
});
const deals = (CR.deals || []).map((d) => omit(d, ["summary"]));
const intel = (CR.intel || []).map((i) => omit(i, ["summary"]));
const funds = (CR.funds || []).map((f) => omit(f, ["sources", "description", "notableInvestments", "investors"]));
const research = CR.research || [];
const HEDGE_INTEL = (CR.HEDGE_INTEL || []).map((h) => omit(h, ["summary"]));
// Compact hedge-fund roster (id + name only) — the reading pane links entity mentions
// to /v2/profiles/#/hf/<id>; nothing else on Home needs the fuller record.
const hedgeFunds = (CR.HEDGE_FUNDS || []).map((h) => pick(h, ["id", "name"]));
const LAST_CHECKED = CR.LAST_CHECKED ?? null;
const LAST_CHECKED_TIME = CR.LAST_CHECKED_TIME ?? null;

// ---- legal -----------------------------------------------------------------
const items = (LG.items || []).map((i) => omit(i, ["summary", "points", "tags", "areas", "jurisdiction", "area"]));
const cases = (LG.cases || []).map((c) => omit(c, ["summary"]));
const restructurings = (LG.restructurings || []).map((r) => omit(r, ["features", "notes", "debt", "creditors", "advisers"]));
const firmById = {};
for (const [id, f] of Object.entries(LG.firmById || {})) firmById[id] = { name: f && f.name };

// ---- macro (kept whole) ----------------------------------------------------
const { NEWS, ARTICLES, COMMENTARY, CYCLE, BUBBLE, OUTLOOK, EARNINGS } = MC;

const J = (v) => JSON.stringify(v);
const EXPORTS = {
  managers, deals, intel, funds, research, HEDGE_INTEL, hedgeFunds, LAST_CHECKED, LAST_CHECKED_TIME,
  items, cases, restructurings, firmById,
  NEWS, ARTICLES, COMMENTARY, CYCLE, BUBBLE, OUTLOOK, EARNINGS,
};
const body = Object.entries(EXPORTS).map(([k, v]) => `export const ${k} = ${J(v)};`).join("\n");
const out = `// GENERATED by scripts/gen-home-data.mjs — DO NOT EDIT.
// Compact desk-data slice for the Home surface: the fields Home + the manager wire
// render, with heavy profile/detail bodies stripped. Regenerated on every build from
// the full credit/legal/macro modules (which the 5×/day refresh edits). Tokenless +
// no-cache (see _headers / sw.js), like ft.js / newsletters.js / briefings.js.
${body}
`;

const dest = resolve(ROOT, "home-data.js");
writeFileSync(dest, out);
const raw = statSync(dest).size, gz = gzipSync(out).length;
console.log(`gen-home-data: wrote home-data.js — ${(raw / 1024).toFixed(0)} KB raw, ${(gz / 1024).toFixed(0)} KB gzip (${managers.length} managers, ${deals.length} deals, ${intel.length} intel, ${items.length} legal items)`);
